"""Statistical treatment of the curve, confidence intervals, paired tests, power.

Reporting point estimates alone invites two errors a reviewer will catch immediately: reading
a small difference as real, and reading a null result as evidence of equivalence. Both appear
in this project's raw numbers, so both are handled explicitly.

Three properties of the evaluation shape the method:

**Checkpoints are paired.** Every scope runs the *same* tasks over the same corpus, so scope A
and scope B are compared checkpoint-by-checkpoint on identical items. That pairing is
information, McNemar's test uses only the discordant pairs and is far more sensitive than
comparing two independent proportions.

**Checkpoints are clustered within tasks.** Five checkpoints from one investigation are not
five independent observations: if the model misreads the case, several fail together. Treating
them as independent understates the standard error, so the bootstrap resamples **tasks**, not
checkpoints.

**The null result needs power, not just a p-value.** "No significant difference" is not
"no difference", with 46 checkpoints a 3-point effect is undetectable, so failing to find one
says nothing. Equivalence is therefore assessed with a TOST-style interval rather than by
accepting a non-significant test.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass
from typing import Sequence

# Fixed so reported intervals are reproducible run to run.
BOOTSTRAP_SEED = 20260813
BOOTSTRAP_SAMPLES = 10_000

# Largest difference treated as practically equivalent. Pre-registered rather than chosen
# after seeing results, and deliberately loose: a 5-point swing in checkpoint score is small
# enough that an institution would not change a protection decision over it.
EQUIVALENCE_MARGIN = 0.05


@dataclass(frozen=True)
class Interval:
    point: float
    low: float
    high: float

    def __str__(self) -> str:
        return f"{self.point:.3f} [{self.low:.3f}, {self.high:.3f}]"


@dataclass(frozen=True)
class PairedComparison:
    """One scope against another, on the same checkpoints."""

    label: str
    n_checkpoints: int
    n_tasks: int
    # Discordant pairs: passed in A but not B, and the reverse.
    a_only: int
    b_only: int
    difference: Interval
    # Significance on the SAME continuous outcome the CI is built from: a paired bootstrap
    # p-value over per-task mean score deltas. This replaces significance-by-McNemar, which
    # tested a *different* variable (binary pass/fail) than the CI reported (partial-credit
    # score), so the two could contradict, a score-CI excluding zero while McNemar returned
    # p=1.000 (the "none vs direct" comparison: 0.024 [0.000, 0.070], p=1.000). CI and p-value are
    # now one matched pair: the CI excludes zero iff this p < 0.05, by construction.
    p_value: float
    # McNemar exact on the binary pass/fail discordant pairs, kept as reported context (it
    # answers a real, if different, question: did the pass/fail *count* move) but no longer
    # drives the verdict, which must agree with the effect it is reported beside.
    mcnemar_p_value: float
    # Smallest true difference this design could reliably detect.
    detectable_effect: float
    # Family-wise adjusted p-value (Holm-Bonferroni), set by `adjust_family` when this
    # comparison is one of several tested together. None for a standalone comparison. When
    # present it drives `significant`/`verdict`: reporting six simultaneous tests each at
    # alpha=0.05 inflates the family-wise false-positive rate to ~0.26, so a "different"
    # verdict in the headline table must clear the corrected bar, not the per-test one.
    adjusted_p_value: float | None = None

    @property
    def effective_p_value(self) -> float:
        """The p-value the verdict is taken on: adjusted within a family, raw when standalone."""
        return self.p_value if self.adjusted_p_value is None else self.adjusted_p_value

    @property
    def significant(self) -> bool:
        return self.effective_p_value < 0.05

    @property
    def verdict(self) -> str:
        """Different, equivalent, or inconclusive, with equivalence held to a real standard.

        An earlier version returned "equivalent" whenever the CI fell inside ±0.05. That
        manufactured equivalence from *no evidence*: when two scopes produce identical
        checkpoint outcomes, every per-task delta is zero, so every bootstrap resample yields
        exactly zero and the interval collapses to [0.000, 0.000], trivially inside the
        threshold. The result was an equivalence claim generated by degenerate variance, at a
        minimum detectable effect of 0.29, which is how the earlier ablation conclusion arose.

        Equivalence now requires two things a genuine result has and an artifact does not:
        the design must be able to *detect* an effect at the equivalence margin, and the
        interval must be non-degenerate.
        """
        if self.significant:
            return "different"

        # A zero-width interval means no variation was observed at all, not that the effect
        # is zero. With one instrument and identical inputs, that is an identity, not a
        # measurement.
        degenerate = self.difference.high - self.difference.low <= 0.0
        if degenerate:
            return "no-variation"

        # TOST-style, with three conditions a genuine equivalence has and a low-information
        # comparison does not: the whole interval sits inside the margin; the design could
        # actually detect an effect at the margin; and there are enough discordant pairs to
        # carry an effect that size (p_d >= margin). The last rules out "equivalent" from the
        # least informative data, the circularity a reviewer flagged, where feeding tiny
        # observed discordance back into the MDE certified equivalence from one flipped pair.
        p_d = (self.a_only + self.b_only) / self.n_checkpoints if self.n_checkpoints else 0.0
        within_margin = (
            abs(self.difference.low) < EQUIVALENCE_MARGIN
            and abs(self.difference.high) < EQUIVALENCE_MARGIN
        )
        if (
            within_margin
            and self.detectable_effect <= EQUIVALENCE_MARGIN
            and p_d >= EQUIVALENCE_MARGIN
        ):
            return "equivalent"
        return "inconclusive"

    def to_dict(self) -> dict:
        return {
            "comparison": self.label,
            "checkpoints": self.n_checkpoints,
            "tasks": self.n_tasks,
            "difference": self.difference.point,
            "ci_low": self.difference.low,
            "ci_high": self.difference.high,
            "p_value": self.p_value,
            "adjusted_p_value": self.adjusted_p_value,
            "mcnemar_p_value": self.mcnemar_p_value,
            "discordant_a_only": self.a_only,
            "discordant_b_only": self.b_only,
            "minimum_detectable_effect": self.detectable_effect,
            "verdict": self.verdict,
        }


def adjust_family(comparisons: "Sequence[PairedComparison]") -> "list[PairedComparison]":
    """Holm-Bonferroni across a family of comparisons, returning copies with `adjusted_p_value`.

    The headline table runs `none` against every other scope simultaneously; interpreting each
    at alpha=0.05 with no correction inflates the family-wise false-positive rate to ~1-0.95**6
    ~= 0.26. Holm-Bonferroni controls that at 0.05 while being uniformly more powerful than
    plain Bonferroni: sort the k p-values ascending, scale the i-th (0-based) by (k - i), enforce
    monotonicity, clamp to 1. A comparison's verdict is then taken on the adjusted p, so a
    "different" claim in the write-up is one that survives the multiplicity of the family.
    """
    import dataclasses

    ordered = sorted(range(len(comparisons)), key=lambda i: comparisons[i].p_value)
    k = len(comparisons)
    adjusted = [0.0] * k
    running = 0.0
    for rank, idx in enumerate(ordered):
        val = min(1.0, comparisons[idx].p_value * (k - rank))
        running = max(running, val)  # Holm's step-down: adjusted p is non-decreasing in rank
        adjusted[idx] = running
    return [
        dataclasses.replace(c, adjusted_p_value=adjusted[i])
        for i, c in enumerate(comparisons)
    ]


def _task_scores(result: dict) -> list[list[float]]:
    """Checkpoint scores grouped by task, preserving the clustering."""
    return [[c["score"] for c in task["checkpoints"]] for task in result["tasks"]]


def bootstrap_mean(result: dict, confidence: float = 0.95) -> Interval:
    """Bootstrap CI for a scope's mean checkpoint score, resampling **tasks**.

    Resampling checkpoints would treat clustered observations as independent and produce an
    interval that is too narrow, the classic error when items share a parent unit.
    """
    clusters = _task_scores(result)
    flat = [s for cluster in clusters for s in cluster]
    if not flat:
        return Interval(0.0, 0.0, 0.0)

    point = sum(flat) / len(flat)
    rng = random.Random(BOOTSTRAP_SEED)
    means: list[float] = []

    for _ in range(BOOTSTRAP_SAMPLES):
        sampled = [clusters[rng.randrange(len(clusters))] for _ in range(len(clusters))]
        scores = [s for cluster in sampled for s in cluster]
        if scores:
            means.append(sum(scores) / len(scores))

    means.sort()
    tail = (1 - confidence) / 2
    return Interval(
        point=point,
        low=means[int(tail * len(means))],
        high=means[int((1 - tail) * len(means)) - 1],
    )


def _bootstrap_two_sided_p(sorted_diffs: Sequence[float]) -> float:
    """Two-sided bootstrap p-value for "the paired difference is zero".

    Computed from the SAME resampled difference distribution the CI is drawn from, so the
    significance test and the reported effect are one matched pair on the continuous outcome:
    p = 2 * min(share of resamples <= 0, share of resamples >= 0), clamped to [0, 1]. A
    resample never straddling zero yields the smallest p the resolution allows (never a hard
    0, which would overstate certainty from a finite bootstrap); an all-zero distribution
    (identical outcomes, no variation) yields 1.0, which the verdict then reads as
    "no-variation" rather than equivalence.
    """
    n = len(sorted_diffs)
    if n == 0:
        return 1.0
    le = sum(1 for d in sorted_diffs if d <= 0.0)
    ge = sum(1 for d in sorted_diffs if d >= 0.0)
    p = 2.0 * min(le, ge) / n
    # A finite bootstrap cannot certify p=0; floor at 1/n so certainty is bounded by the
    # resolution of the resample.
    return min(1.0, max(p, 1.0 / n if min(le, ge) == 0 else 0.0))


def _mcnemar_exact(a_only: int, b_only: int) -> float:
    """Two-sided exact McNemar p-value from the discordant counts.

    Exact rather than chi-square: with few discordant pairs the asymptotic approximation is
    unreliable, and few discordant pairs is exactly the regime here.
    """
    n = a_only + b_only
    if n == 0:
        return 1.0

    def binom_pmf(k: int) -> float:
        return math.comb(n, k) * (0.5**n)

    observed = min(a_only, b_only)
    tail = sum(binom_pmf(k) for k in range(observed + 1))
    return min(1.0, 2 * tail)


def _minimum_detectable_effect(
    n: int, discordance: float = 0.5, power: float = 0.80, alpha: float = 0.05
) -> float:
    """Smallest difference this design could detect, for a **paired** McNemar test.

    The earlier formula, `(z_a + z_b) * sqrt(0.5 / n)`, is the MDE for two *independent*
    proportions at worst-case variance, it ignores the pairing that makes this design
    sensitive in the first place. McNemar's power depends on the rate of **discordant pairs**,
    not on n alone:

        d = (z_a + z_b) * sqrt(p_d / n)

    The two coincide only when p_d = 0.5, which is the worst case. Using the unpaired form
    therefore *overstated* the MDE, so genuinely detectable effects were being reported as
    underpowered, and the headline "4,356 checkpoints needed" was inflated by `0.5 / p_d`.

    Two guards against over-reading, both added after a reviewer showed the naive form is
    circular and can report an MDE *larger than any effect the data could carry*:

      * **Feasibility cap.** The observed effect is δ = (p10 - p01), so |δ| <= p_d always.
        A reported MDE above the measured discordance describes a detectable effect the
        design cannot express; it is capped at p_d.
      * **No measured-discordance optimism.** Feeding the observed p_d back in shrinks the
        MDE on exactly the least informative data, which is why the equivalence verdict also
        requires p_d >= the margin (enforced in `compare_scopes`, not here).

    `discordance` is measured from the comparison where available, and defaults to the
    worst case so an unknown is never optimistic.
    """
    if n <= 0:
        return 1.0
    z_alpha, z_beta = 1.96, 0.84  # two-sided 0.05, power 0.80
    p_d = discordance if discordance > 0 else 0.5
    raw = (z_alpha + z_beta) * math.sqrt(p_d / n)
    # Cap at the largest effect this discordance can produce: an MDE above p_d is not a
    # sensitivity this instrument possesses.
    return min(raw, p_d) if discordance > 0 else raw


def compare_scopes(result_a: dict, result_b: dict, label: str | None = None) -> PairedComparison:
    """Paired comparison of two scopes over identical checkpoints."""
    scores_a = {
        c["checkpoint_id"]: c
        for task in result_a["tasks"]
        for c in task["checkpoints"]
    }
    scores_b = {
        c["checkpoint_id"]: c
        for task in result_b["tasks"]
        for c in task["checkpoints"]
    }
    shared = sorted(set(scores_a) & set(scores_b))

    a_only = sum(
        1 for k in shared if scores_a[k]["passed"] and not scores_b[k]["passed"]
    )
    b_only = sum(
        1 for k in shared if scores_b[k]["passed"] and not scores_a[k]["passed"]
    )

    # Bootstrap the *paired difference*, again resampling tasks to respect clustering.
    tasks_a = {t["task_id"]: t for t in result_a["tasks"]}
    tasks_b = {t["task_id"]: t for t in result_b["tasks"]}
    common_tasks = sorted(set(tasks_a) & set(tasks_b))

    def paired_difference(task_ids: Sequence[str]) -> float:
        deltas: list[float] = []
        for task_id in task_ids:
            by_id_b = {c["checkpoint_id"]: c["score"] for c in tasks_b[task_id]["checkpoints"]}
            for checkpoint in tasks_a[task_id]["checkpoints"]:
                other = by_id_b.get(checkpoint["checkpoint_id"])
                if other is not None:
                    deltas.append(checkpoint["score"] - other)
        return sum(deltas) / len(deltas) if deltas else 0.0

    point = paired_difference(common_tasks)
    rng = random.Random(BOOTSTRAP_SEED)
    diffs: list[float] = []
    for _ in range(BOOTSTRAP_SAMPLES):
        resampled = [common_tasks[rng.randrange(len(common_tasks))] for _ in common_tasks]
        diffs.append(paired_difference(resampled))
    diffs.sort()

    return PairedComparison(
        label=label or f"{result_a['scope']} vs {result_b['scope']}",
        n_checkpoints=len(shared),
        n_tasks=len(common_tasks),
        a_only=a_only,
        b_only=b_only,
        difference=Interval(
            point=point,
            low=diffs[int(0.025 * len(diffs))],
            high=diffs[int(0.975 * len(diffs)) - 1],
        ),
        # Significance from the SAME bootstrap distribution as the CI, so the two never
        # disagree. Two-sided p = 2 * min(share of resamples <= 0, share >= 0), the standard
        # bootstrap-hypothesis-test construction on the effect the CI is reported for.
        p_value=_bootstrap_two_sided_p(diffs),
        mcnemar_p_value=_mcnemar_exact(a_only, b_only),
        detectable_effect=_minimum_detectable_effect(
            len(shared),
            # Measured discordance rather than the worst-case assumption: this is what
            # actually determines McNemar's power on this comparison.
            discordance=(a_only + b_only) / len(shared) if shared else 0.5,
        ),
    )


def required_sample_size(
    effect: float, discordance: float = 0.5, power: float = 0.80, alpha: float = 0.05
) -> int:
    """Checkpoints needed to detect `effect` at the given power, for a paired design.

    Inverts the McNemar MDE above. Defaults to worst-case discordance so the figure is never
    optimistic; supply the measured rate for a realistic number.
    """
    if effect <= 0:
        return 0
    z_alpha, z_beta = 1.96, 0.84
    p_d = discordance if discordance > 0 else 0.5
    return math.ceil(p_d * ((z_alpha + z_beta) / effect) ** 2)
